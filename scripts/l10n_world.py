from __future__ import annotations

PIDS = [
    "lotus-dot", "simple-flower", "peacock", "diya", "pulli", "spiral",
    "eight-petal", "geo-star", "festival-flower", "mandala", "butterfly",
    "pongal-pot", "sikku-knot", "onam-pookalam", "sun-burst", "mango-leaf",
]


def patterns(titles: list[str], notes: list[str]) -> dict[str, str]:
    if not (len(titles) == len(notes) == len(PIDS)):
        raise ValueError(f"pattern counts {len(titles)} {len(notes)} {len(PIDS)}")
    out: dict[str, str] = {}
    for pid, title, note in zip(PIDS, titles, notes):
        out[f"pattern.{pid}.title"] = title
        out[f"pattern.{pid}.note"] = note
    return out


